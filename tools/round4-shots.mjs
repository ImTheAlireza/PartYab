import { chromium as pw } from 'playwright';
import chromium, { inflate, setupLambdaEnvironment } from '@sparticuz/chromium';
await inflate('node_modules/@sparticuz/chromium/bin/al2023.tar.br'); setupLambdaEnvironment('/tmp/al2023/lib');
const b = await pw.launch({ executablePath: await chromium.executablePath(), args: [...chromium.args, '--enable-unsafe-swiftshader'], headless: true });
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
p.setDefaultTimeout(60000);
const no3d = () => p.route('**/assets/js/hero-3d.js', r => r.fulfill({ contentType: 'text/javascript', body: '' }));
const yes3d = () => p.unroute('**/assets/js/hero-3d.js');
const clipY = async (sel, h, pad = 80) => { const r = await p.locator(sel).first().boundingBox(); return { x: 0, y: Math.max(0, r.y - pad), width: 1440, height: h }; };
await no3d();
await p.goto('http://127.0.0.1:3000/', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(700);
await p.locator('.pb-nav__menu > li > a').nth(1).hover(); await p.locator('.pb-action').first().hover(); await p.waitForTimeout(400);
await p.screenshot({ path: 'preview/round4-header-hover.png', clip: { x: 0, y: 0, width: 1440, height: 170 } });
const cat = p.locator('.pb-cat').first(); await cat.scrollIntoViewIfNeeded(); await p.waitForTimeout(700); await cat.hover(); await p.waitForTimeout(600);
await p.screenshot({ path: 'preview/round4-category-hover.png', clip: await clipY('.pb-cats', 300, 40) });
await p.locator('.pb-marquee').scrollIntoViewIfNeeded(); await p.waitForTimeout(400);
await p.screenshot({ path: 'preview/round4-brands.png', clip: await clipY('.pb-marquee', 260, 90) });
await p.goto('http://127.0.0.1:3000/contact', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(400);
await p.locator('[name=phone]').focus(); await p.waitForTimeout(300);
await p.screenshot({ path: 'preview/round4-focus.png', clip: await clipY('[name=phone]', 320, 140) });
await p.evaluate(() => window.PartyabTransition.show()); await p.waitForTimeout(700);
await p.screenshot({ path: 'preview/round4-loader-active.png' });
await p.evaluate(() => window.PartyabTransition.hide()); await p.waitForTimeout(220);
await p.screenshot({ path: 'preview/round4-loader-slide.png' });
await p.waitForTimeout(600);
await yes3d();
await p.goto('http://127.0.0.1:3000/', { waitUntil: 'domcontentloaded' });
await p.waitForFunction(() => window.PartyabHero3D?.ready, { timeout: 30000 }); await p.waitForTimeout(1500);
await p.screenshot({ path: 'preview/round4-hero.png' });
await p.setViewportSize({ width: 390, height: 844 }); await p.waitForTimeout(900);
await p.screenshot({ path: 'preview/round4-hero-mobile.png' });
console.log('shots done');
await b.close();
