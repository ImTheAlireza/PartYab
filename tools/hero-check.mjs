import { chromium as pw } from 'playwright';
import chromium, { inflate, setupLambdaEnvironment } from '@sparticuz/chromium';
await inflate('node_modules/@sparticuz/chromium/bin/al2023.tar.br'); setupLambdaEnvironment('/tmp/al2023/lib');
const b = await pw.launch({ executablePath: await chromium.executablePath(), args: [...chromium.args, '--enable-unsafe-swiftshader'], headless: true });
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errors=[]; p.on('pageerror',e=>errors.push(e.message)); p.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await p.goto('http://127.0.0.1:3000/',{waitUntil:'domcontentloaded'});
await p.waitForFunction(()=>window.PartyabHero3D?.ready,{timeout:30000});
await p.waitForTimeout(1200);
const before = await p.evaluate(()=>window.PartyabHero3D);
await p.screenshot({path:'preview/round4-hero.png',timeout:60000});
await p.evaluate(()=>window.scrollTo({top:500,behavior:'instant'}));
await p.waitForFunction(()=>window.PartyabHero3D?.progress > .3,{timeout:10000});
await p.waitForTimeout(700);
const after = await p.evaluate(()=>window.PartyabHero3D);
await p.screenshot({path:'preview/round4-hero-scroll.png',timeout:60000});
console.log('before', before, 'after', after, 'rotated', Math.abs(after.yaw-before.yaw)>.1);
console.log('ERRORS', errors);
await b.close();
