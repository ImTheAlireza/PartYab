import { chromium as pw } from 'playwright';
import chromium, { inflate, setupLambdaEnvironment } from '@sparticuz/chromium';
await inflate('node_modules/@sparticuz/chromium/bin/al2023.tar.br'); setupLambdaEnvironment('/tmp/al2023/lib');
const b = await pw.launch({ executablePath: await chromium.executablePath(), args: chromium.args, headless: true });
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
await p.route('**/assets/js/hero-3d.js', r => r.fulfill({ contentType: 'text/javascript', body: '' }));
await p.goto('http://127.0.0.1:3000/contact', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(500);
await p.evaluate(() => { window.PartyabTransition.show(); });
await p.waitForFunction(() => document.querySelector('.pb-page-loader').classList.contains('is-active') && getComputedStyle(document.querySelector('.pb-page-loader')).transform === 'none');
await p.waitForTimeout(900);
await p.screenshot({ path: 'preview/l2-loader-active.png' });
const waves = await p.locator('.pb-page-loader__wave').evaluateAll(els => els.map(el => ({ anim: getComputedStyle(el).animationName, delay: getComputedStyle(el).animationDelay, opacity: getComputedStyle(el).opacity })));
console.log('waves', JSON.stringify(waves));
await p.evaluate(() => { window.PartyabTransition.hide(); }); await p.waitForTimeout(180);
await p.screenshot({ path: 'preview/l2-loader-slide.png' });
await p.waitForFunction(() => document.querySelector('.pb-page-loader').hidden);
await p.emulateMedia({ reducedMotion: 'reduce' });
await p.evaluate(() => { window.PartyabTransition.show(); }); await p.waitForTimeout(120);
console.log('reduced', await p.locator('.pb-page-loader').evaluate(el => ({ static: el.classList.contains('is-static'), waveAnim: getComputedStyle(el.querySelector('.pb-page-loader__wave')).animationName, logoAnim: getComputedStyle(el.querySelector('.pb-page-loader__logo')).animationName })));
await b.close();
