/**
 * ساخت/به‌روزرسانی صفحه‌های ثابت و اتصال به منوی فوتر.
 *
 * @param array $report گزارش.
 */
function partyab_qs_step_pages( array &$report ): void {
	$created = 0;
	$ids     = array();

	foreach ( partyab_qs_static_pages() as $slug => $page ) {
		$id = partyab_qs_create_page( $page['title'], $slug, $page['content'] );

		if ( $id > 0 ) {
			++$created;
			$ids[ $slug ] = $id;

			wp_update_post( array(
				'ID'           => $id,
				'post_title'   => $page['title'],
				'post_content' => $page['content'],
			) );

			// قالب محتوایی اختصاصی تا متن در عرض خوانا بماند (سبد و حساب قالب خودشان را دارند).
			update_post_meta( $id, '_wp_page_template', 'page-content.php' );
		}
	}

	partyab_qs_log( $report, 'محتوا', 'صفحه‌های ثابت', $created === count( partyab_qs_static_pages() ), $created . ' صفحه آماده شد' );

	// منوی فوتر
	$menu_name = 'منوی فوتر';
	$menu      = wp_get_nav_menu_object( $menu_name );
	$menu_id   = $menu ? (int) $menu->term_id : (int) wp_create_nav_menu( $menu_name );

	if ( $menu_id && ! is_wp_error( $menu_id ) ) {
		if ( ! $menu ) {
			$pages = partyab_qs_static_pages();

			foreach ( $ids as $slug => $id ) {
				wp_update_nav_menu_item(
					$menu_id,
					0,
					array(
						'menu-item-title'     => $pages[ $slug ]['title'],
						'menu-item-object'    => 'page',
						'menu-item-object-id' => $id,
						'menu-item-type'      => 'post_type',
						'menu-item-status'    => 'publish',
					)
				);
			}
		}

		$locations                   = (array) get_theme_mod( 'nav_menu_locations', array() );
		$locations['partyab-footer'] = $menu_id;
		set_theme_mod( 'nav_menu_locations', $locations );

		partyab_qs_log( $report, 'محتوا', 'منوی فوتر', true, count( $ids ) . ' لینک صفحه محتوایی اضافه شد' );
	}
